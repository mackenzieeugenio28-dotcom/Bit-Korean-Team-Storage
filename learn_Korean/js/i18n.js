const Lang = {
  key: 'kdrama_lang',
  current: 'en',

  init() {
    const saved = localStorage.getItem(this.key);
    this.current = (saved === 'zh' || saved === 'en') ? saved : 'en';
    document.documentElement.lang = this.current === 'zh' ? 'zh-CN' : 'en';
  },

  set(lang) {
    this.current = lang;
    localStorage.setItem(this.key, lang);
    document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
    applyI18n();
    document.dispatchEvent(new CustomEvent('langchange', { detail: { lang } }));
  },

  t(key, params) {
    let text = (I18N[this.current] && I18N[this.current][key]) !== undefined
      ? I18N[this.current][key]
      : (I18N.en[key] !== undefined ? I18N.en[key] : key);
    if (params) {
      for (const k of Object.keys(params)) {
        text = text.split('{' + k + '}').join(params[k]);
      }
    }
    return text;
  },
};

function applyI18n() {
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    el.textContent = Lang.t(key);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
    const key = el.getAttribute('data-i18n-placeholder');
    el.setAttribute('placeholder', Lang.t(key));
  });
  document.querySelectorAll('[data-i18n-title]').forEach((el) => {
    const key = el.getAttribute('data-i18n-title');
    el.setAttribute('title', Lang.t(key));
  });
}
